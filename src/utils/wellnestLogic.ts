export interface CautiousDietContext {
  recommendedPatternId: DietPatternId;
  note: string;
}

export function buildCautiousDietContext(
  findings: ExtractedFinding[],
): CautiousDietContext {
  const confirmedOutside = findings.filter(
    (f) => f.confirmedByUser && f.rangeStatus === 'outside_range',
  );

  const hasLipidOutside = confirmedOutside.some((f) =>
    /ldl|cholesterol|triglyceride/i.test(f.testName),
  );
  const hasVitaminDOutside = confirmedOutside.some((f) =>
    /vitamin\s*d|25-hydroxy/i.test(f.testName),
  );

  if (hasLipidOutside && hasVitaminDOutside) {
    return {
      recommendedPatternId: 'heart_lipid',
      note: 'Your confirmed results include lipid and Vitamin D values outside their report ranges. Explore the Heart & Lipid or Vitamin D patterns below as general topics to review with your clinician.',
    };
  }

  if (hasLipidOutside) {
    return {
      recommendedPatternId: 'heart_lipid',
      note: 'A confirmed lipid value sits outside its report range. The Heart & Lipid pattern below highlights gradual soluble-fiber and unsaturated-fat ideas to discuss with your doctor.',
    };
  }

  if (hasVitaminDOutside) {
    return {
      recommendedPatternId: 'vitamin_d_recovery',
      note: 'A confirmed Vitamin D value sits outside its report range. Review the Vitamin D & Recovery food ideas below alongside clinician guidance on supplementation.',
    };
  }

  return {
    recommendedPatternId: 'balanced',
    note: 'General whole-food nutrition ideas for everyday wellbeing. Confirm any pending lab items first and consult a qualified clinician or registered dietitian before major dietary changes.',
  };
}

