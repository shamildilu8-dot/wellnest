export const MAX_UPLOAD_BYTES = 10 * 1024 * 1024; // 10 MB

export const ALLOWED_MIME_TYPES = new Set([
  'application/pdf',
  'image/png',
  'image/jpeg',
  'text/plain',
  'text/csv',
  'application/json',
]);

export const ALLOWED_EXTENSIONS = new Set([
  '.pdf',
  '.png',
  '.jpg',
  '.jpeg',
  '.txt',
  '.csv',
  '.json',
]);

export interface UploadValidationResult {
  valid: boolean;
  error?: string;
}

export function validateUploadFile(
  fileName: string,
  mimeType: string,
  sizeBytes: number,
): UploadValidationResult {
  const lowerName = fileName.trim().toLowerCase();
  const dotIdx = lowerName.lastIndexOf('.');
  const ext = dotIdx >= 0 ? lowerName.slice(dotIdx) : '';

  if (!ext || !ALLOWED_EXTENSIONS.has(ext)) {
    return {
      valid: false,
      error:
        'Unsupported file extension. Please upload a PDF, PNG, JPG, TXT, CSV, or JSON report.',
    };
  }

  if (mimeType && !ALLOWED_MIME_TYPES.has(mimeType.toLowerCase())) {
    // Allow empty mimeType on some browsers for .csv/.json, but reject disallowed known mimes
    return {
      valid: false,
      error: `Unsupported file type (${mimeType}). Allowed types: PDF, PNG, JPG, TXT, CSV, JSON.`,
    };
  }

  if (!Number.isFinite(sizeBytes) || sizeBytes <= 0) {
    return {
      valid: false,
      error: 'The selected file appears to be empty.',
    };
  }

  if (sizeBytes > MAX_UPLOAD_BYTES) {
    return {
      valid: false,
      error: 'File exceeds the 10 MB security limit. Please upload a smaller report.',
    };
  }

  return { valid: true };
}

export interface RawDnaDetectionResult {
  isRawDna: boolean;
  reason?: string;
}

/**
 * Prevents analyzing raw consumer DNA genotype files (23andMe, AncestryDNA, VCF, MyHeritage).
 * Wellnest only accepts professionally interpreted clinical genetic reports.
 */
export function detectRawDnaContent(
  textContent: string,
  fileName = '',
): RawDnaDetectionResult {
  const lowerName = fileName.toLowerCase();
  if (
    lowerName.endsWith('.vcf') ||
    lowerName.endsWith('.fastq') ||
    lowerName.endsWith('.bam') ||
    lowerName.includes('23andme') ||
    lowerName.includes('ancestrydna') ||
    lowerName.includes('raw_dna') ||
    lowerName.includes('raw-dna') ||
    lowerName.includes('genome_raw')
  ) {
    return {
      isRawDna: true,
      reason:
        'Raw DNA files (such as 23andMe, AncestryDNA, or VCF genotype exports) cannot be analyzed. Wellnest only accepts professionally interpreted clinical genetic reports.',
    };
  }

  const sample = textContent.slice(0, 12000);
  const lowerSample = sample.toLowerCase();

  const rawHeaderMarkers = [
    '# rsid\tchromosome\tposition\tgenotype',
    'rsid\tchromosome\tposition\tallele1\tallele2',
    'rsid,chromosome,position,result',
    '##fileformat=vcf',
    'this data file generated by 23andme',
    'ancestrydna raw data',
    'myheritage dna raw data',
  ];

  if (rawHeaderMarkers.some((marker) => lowerSample.includes(marker))) {
    return {
      isRawDna: true,
      reason:
        'Detected raw genetic genotype data. Wellnest does not analyze raw DNA files or predict disease from SNP lists. Please upload a professionally interpreted genetic report instead.',
    };
  }

  // Count lines matching raw SNP rows: rs12345 <tab/comma> chr <tab/comma> pos <tab/comma> AA/AG/CT
  const lines = sample.split(/\r?\n/).slice(0, 80);
  let snpRowCount = 0;
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    if (/^rs\d+[\t,;]+(\d+|x|y|mt)[\t,;]+\d+[\t,;]+[acgtid\-]{1,4}/i.test(trimmed)) {
      snpRowCount += 1;
    }
  }

  if (snpRowCount >= 3) {
    return {
      isRawDna: true,
      reason:
        'Detected raw SNP genotype rows (rsID/chromosome/allele format). Wellnest never analyzes raw DNA files. Only professionally interpreted clinical genetic reports are supported.',
    };
  }

  return { isRawDna: false };
}

export interface ParsedRange {
  kind: 'between' | 'less_than' | 'greater_than' | 'qualitative' | 'unknown';
  min?: number;
  max?: number;
  expectedQualitative?: string;
}

export function parseReferenceRange(rangeText: string): ParsedRange {
  const cleaned = rangeText
    .replace(/–|—/g, '-')
    .replace(/,/g, '')
    .trim();

  if (!cleaned) {
    return { kind: 'unknown' };
  }

  // e.g. "70 - 99" or "0.40-4.50 mg/dL"
  const betweenMatch = cleaned.match(
    /(-?\d+(?:\.\d+)?)\s*(?:-|to)\s*(-?\d+(?:\.\d+)?)/i,
  );
  if (betweenMatch) {
    const min = Number(betweenMatch[1]);
    const max = Number(betweenMatch[2]);
    if (Number.isFinite(min) && Number.isFinite(max) && min <= max) {
      return { kind: 'between', min, max };
    }
  }

  // e.g. "< 200" or "<= 5.7"
  const ltMatch = cleaned.match(/^(?:<|<=|less\s+than)\s*(-?\d+(?:\.\d+)?)/i);
  if (ltMatch) {
    const max = Number(ltMatch[1]);
    if (Number.isFinite(max)) {
      return { kind: 'less_than', max };
    }
  }

  // e.g. "> 40" or ">= 60"
  const gtMatch = cleaned.match(/^(?:>|>=|greater\s+than)\s*(-?\d+(?:\.\d+)?)/i);
  if (gtMatch) {
    const min = Number(gtMatch[1]);
    if (Number.isFinite(min)) {
      return { kind: 'greater_than', min };
    }
  }

  // Qualitative ranges like "Negative" or "Non-reactive"
  if (/^(negative|non-reactive|normal|not detected)$/i.test(cleaned)) {
    return { kind: 'qualitative', expectedQualitative: cleaned.toLowerCase() };
  }

  return { kind: 'unknown' };
}

export function evaluateBiomarkerAgainstReportRange(
  resultText: string,
  unit: string,
  rangeText: string,
  category: ReportCategory = 'lab',
): { status: RangeStatus; explanation: string } {
  if (category === 'interpreted_genetic') {
    return {
      status: 'interpreted_finding',
      explanation:
        'Professionally interpreted genetic risk information. Review with a clinician or genetic counselor.',
    };
  }

  const trimmedResult = resultText.trim();
  const trimmedRange = rangeText.trim();
  const trimmedUnit = unit.trim();

  if (!trimmedResult || !trimmedRange || !trimmedUnit) {
    return {
      status: 'needs_review',
      explanation:
        'Missing result, unit, or report reference range. Please confirm against the original report.',
    };
  }

  const parsedRange = parseReferenceRange(trimmedRange);
  if (parsedRange.kind === 'qualitative') {
    const normRes = trimmedResult.toLowerCase();
    if (normRes === parsedRange.expectedQualitative) {
      return {
        status: 'within_range',
        explanation: "Matches this report's reference range.",
      };
    }
    return {
      status: 'outside_range',
      explanation:
        "Differs from this report's reference value. Discuss with a qualified clinician.",
    };
  }

  const numericMatch = trimmedResult.replace(/,/g, '').match(/-?\d+(?:\.\d+)?/);
  if (!numericMatch || parsedRange.kind === 'unknown') {
    return {
      status: 'needs_review',
      explanation:
        'Could not automatically verify against the stated reference range. Please confirm manually.',
    };
  }

  const numericValue = Number(numericMatch[0]);
  if (!Number.isFinite(numericValue)) {
    return {
      status: 'needs_review',
      explanation: 'Non-numeric value requires user confirmation.',
    };
  }

  if (
    parsedRange.kind === 'between' &&
    parsedRange.min !== undefined &&
    parsedRange.max !== undefined
  ) {
    const inRange =
      numericValue >= parsedRange.min && numericValue <= parsedRange.max;
    return inRange
      ? {
          status: 'within_range',
          explanation: "Within this report's reference range.",
        }
      : {
          status: 'outside_range',
          explanation:
            "Outside this report's reference range. This is educational information, not a diagnosis.",
        };
  }

  if (parsedRange.kind === 'less_than' && parsedRange.max !== undefined) {
    const inRange = trimmedRange.includes('<=')
      ? numericValue <= parsedRange.max
      : numericValue < parsedRange.max;
    return inRange
      ? {
          status: 'within_range',
          explanation: "Within this report's reference range.",
        }
      : {
          status: 'outside_range',
          explanation:
            "Outside this report's reference range. This is educational information, not a diagnosis.",
        };
  }

  if (parsedRange.kind === 'greater_than' && parsedRange.min !== undefined) {
    const inRange = trimmedRange.includes('>=')
      ? numericValue >= parsedRange.min
      : numericValue > parsedRange.min;
    return inRange
      ? {
          status: 'within_range',
          explanation: "Within this report's reference range.",
        }
      : {
          status: 'outside_range',
          explanation:
            "Outside this report's reference range. This is educational information, not a diagnosis.",
        };
  }

  return {
    status: 'needs_review',
    explanation: 'Reference range requires manual confirmation.',
  };
}

export function normalizeUnit(unit: string): string {
  return unit.trim().toLowerCase().replace(/\s+/g, '');
}

/**
 * Ensures two lab values are never compared blindly across different units or reference ranges.
 */
export function canCompareLabValues(
  a: Pick<ExtractedFinding, 'testName' | 'unit' | 'referenceRange' | 'category'>,
  b: Pick<ExtractedFinding, 'testName' | 'unit' | 'referenceRange' | 'category'>,
): { comparable: boolean; reason?: string } {
  if (a.category !== 'lab' || b.category !== 'lab') {
    return {
      comparable: false,
      reason: 'Genetic findings are interpreted individually rather than numerically compared.',
    };
  }
  if (a.testName.trim().toLowerCase() !== b.testName.trim().toLowerCase()) {
    return { comparable: false, reason: 'Different test names.' };
  }
  if (normalizeUnit(a.unit) !== normalizeUnit(b.unit)) {
    return {
      comparable: false,
      reason: `Units differ (${a.unit || 'none'} vs ${b.unit || 'none'}). Do not compare without unit conversion.`,
    };
  }
  if (
    a.referenceRange.trim().toLowerCase() !==
    b.referenceRange.trim().toLowerCase()
  ) {
    return {
      comparable: false,
      reason:
        "The labs' reference ranges differ, so direct comparison may be misleading.",
    };
  }
  return { comparable: true };
}

export function getRangeStatusLabel(status: RangeStatus): string {
  switch (status) {
    case 'within_range':
      return "Within this report's reference range";
    case 'outside_range':
      return "Outside this report's reference range";
    case 'interpreted_finding':
      return 'Professionally interpreted risk info';
    case 'needs_review':
    default:
      return 'Needs confirmation';
  }
}

/**
 * Deterministic parser for structured lab/interpreted genetic report text or CSV/JSON.
 * Marks uncertain rows when unit, date, or reference range are missing or ambiguous.
 */
export function parseLabReportText(
  rawText: string,
  reportDate: string,
  category: ReportCategory,
  reportId: string,
): ExtractedFinding[] {
  const trimmed = rawText.trim();
  if (!trimmed) return [];

  // Try JSON array format first
  if (trimmed.startsWith('[') || trimmed.startsWith('{')) {
    try {
      const parsed = JSON.parse(trimmed);
      const list = Array.isArray(parsed)
        ? parsed
        : Array.isArray(parsed.findings)
          ? parsed.findings
          : [];
      if (list.length > 0) {
        return list.map((item: Record<string, unknown>, idx: number) => {
          const testName = String(item.testName ?? item.test ?? '').trim();
          const result = String(item.result ?? item.value ?? '').trim();
          const unit = String(item.unit ?? '').trim();
          const date = String(item.reportDate ?? item.date ?? reportDate).trim();
          const referenceRange = String(
            item.referenceRange ?? item.range ?? '',
          ).trim();
          const missingFields: string[] = [];
          if (!testName) missingFields.push('test name');
          if (!result) missingFields.push('result');
          if (category === 'lab' && !unit) missingFields.push('unit');
          if (category === 'lab' && !referenceRange)
            missingFields.push('reference range');
          if (!date) missingFields.push('date');

          const evalRes = evaluateBiomarkerAgainstReportRange(
            result,
            unit,
            referenceRange,
            category,
          );
          const uncertain =
            missingFields.length > 0 || evalRes.status === 'needs_review';

          return {
            id: `${reportId}-f-${idx + 1}`,
            reportId,
            category,
            testName: testName || `Unlabeled test #${idx + 1}`,
            result: result || 'Unclear',
            unit: unit || (category === 'interpreted_genetic' ? 'Report text' : ''),
            reportDate: date || reportDate,
            referenceRange,
            rangeStatus: uncertain && category === 'lab' ? 'needs_review' : evalRes.status,
            uncertain,
            uncertaintyReason:
              missingFields.length > 0
                ? `Missing or unclear: ${missingFields.join(', ')}. Confirm before saving.`
                : evalRes.status === 'needs_review'
                  ? evalRes.explanation
                  : undefined,
            confirmedByUser: false,
            geneOrMarker: item.geneOrMarker ? String(item.geneOrMarker) : undefined,
            clinicalInterpretation: item.clinicalInterpretation
              ? String(item.clinicalInterpretation)
              : undefined,
          };
        });
      }
    } catch {
      // Fall through to line parser
    }
  }

  const lines = trimmed
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter(Boolean);

  const findings: ExtractedFinding[] = [];

  for (let i = 0; i < lines.length; i += 1) {
    const line = lines[i];
    // Skip obvious CSV headers
    if (
      i === 0 &&
      /test\s*name|biomarker/i.test(line) &&
      /result|value/i.test(line)
    ) {
      continue;
    }

    // Format 1: "Test Name: 24 ng/mL (Ref: 30 - 100 ng/mL)" or "Test Name | 24 | ng/mL | 30 - 100 | 2026-10-12"
    if (line.includes('|') || (line.includes(',') && line.split(',').length >= 3)) {
      const sep = line.includes('|') ? '|' : ',';
      const cols = line.split(sep).map((c) => c.trim());
      const testName = cols[0] ?? '';
      const result = cols[1] ?? '';
      const unit = cols[2] ?? '';
      const referenceRange = cols[3] ?? '';
      const date = cols[4] || reportDate;

      if (!testName && !result) continue;

      const missing: string[] = [];
      if (!testName) missing.push('test name');
      if (!result) missing.push('result');
      if (category === 'lab' && !unit) missing.push('unit');
      if (category === 'lab' && !referenceRange) missing.push('reference range');
      if (!date) missing.push('date');

      const evalRes = evaluateBiomarkerAgainstReportRange(
        result,
        unit,
        referenceRange,
        category,
      );
      const uncertain = missing.length > 0 || evalRes.status === 'needs_review';

      findings.push({
        id: `${reportId}-f-${findings.length + 1}`,
        reportId,
        category,
        testName: testName || `Line ${i + 1}`,
        result,
        unit,
        reportDate: date,
        referenceRange,
        rangeStatus: uncertain && category === 'lab' ? 'needs_review' : evalRes.status,
        uncertain,
        uncertaintyReason:
          missing.length > 0
            ? `Missing or uncertain: ${missing.join(', ')}. Please verify against your original document.`
            : evalRes.status === 'needs_review'
              ? evalRes.explanation
              : undefined,
        confirmedByUser: false,
      });
      continue;
    }

    // Format 2: "Vitamin D (25-OH): 24 ng/mL (Ref: 30 - 100)"
    const colonMatch = line.match(
      /^([^:]+):\s*([^\(\n]+?)(?:\s*\((?:Ref|Reference|Range)[:\s]*([^\)]+)\))?$/i,
    );
    if (colonMatch) {
      const testName = colonMatch[1].trim();
      const valAndUnit = colonMatch[2].trim();
      const referenceRange = (colonMatch[3] ?? '').trim();

      const valUnitMatch = valAndUnit.match(
        /^([<>]?\s*-?\d+(?:\.\d+)?)\s*(.*)$/,
      );
      const result = valUnitMatch ? valUnitMatch[1].trim() : valAndUnit;
      const unit = valUnitMatch ? valUnitMatch[2].trim() : '';

      const missing: string[] = [];
      if (category === 'lab' && !unit) missing.push('unit');
      if (category === 'lab' && !referenceRange) missing.push('reference range');
      if (!reportDate) missing.push('date');
      if (/\?|approx|unclear/i.test(line)) missing.push('low-confidence OCR text');

      const evalRes = evaluateBiomarkerAgainstReportRange(
        result,
        unit,
        referenceRange,
        category,
      );
      const uncertain = missing.length > 0 || evalRes.status === 'needs_review';

      findings.push({
        id: `${reportId}-f-${findings.length + 1}`,
        reportId,
        category,
        testName,
        result,
        unit,
        reportDate,
        referenceRange,
        rangeStatus: uncertain && category === 'lab' ? 'needs_review' : evalRes.status,
        uncertain,
        uncertaintyReason:
          missing.length > 0
            ? `Uncertain extraction (${missing.join(', ')}). Confirm before using.`
            : evalRes.status === 'needs_review'
              ? evalRes.explanation
              : undefined,
        confirmedByUser: false,
      });
    }
  }

  return findings;
}

export interface WellbeingCheckInInput {
  energyLevel: number;
  sleepQuality: number;
  stressSelfRating: number;
  sleepHours?: string | number;
  movementMinutes?: string | number;
  restingHeartRateBpm?: string | number;
  systolicMmHg?: string | number;
  diastolicMmHg?: string | number;
  moodNote?: string;
}

export interface WellbeingCheckInValidationResult {
  valid: boolean;
  error?: string;
  normalized?: Omit<WellbeingCheckIn, 'id' | 'date' | 'isDemo'>;
}

function parseOptionalNumberField(
  raw: string | number | undefined,
  label: string,
  min: number,
  max: number,
  integerOnly: boolean,
): { ok: boolean; value?: number; error?: string } {
  if (raw === undefined || raw === null) return { ok: true };
  const str = String(raw).trim();
  if (!str) return { ok: true };

  const num = Number(str);
  if (!Number.isFinite(num)) {
    return { ok: false, error: `${label} must be a valid number.` };
  }
  if (integerOnly && !Number.isInteger(num)) {
    return { ok: false, error: `${label} must be a whole number.` };
  }
  if (num < min || num > max) {
    return {
      ok: false,
      error: `${label} must be between ${min} and ${max}.`,
    };
  }
  return { ok: true, value: integerOnly ? num : Math.round(num * 10) / 10 };
}

export function validateWellbeingCheckInInput(
  input: WellbeingCheckInInput,
): WellbeingCheckInValidationResult {
  const ratings: Array<[string, number]> = [
    ['Energy level', input.energyLevel],
    ['Sleep quality', input.sleepQuality],
    ['Self-rated stress', input.stressSelfRating],
  ];
  for (const [label, val] of ratings) {
    if (!Number.isInteger(val) || val < 1 || val > 5) {
      return {
        valid: false,
        error: `${label} must be a whole number between 1 and 5.`,
      };
    }
  }

  const sleepHours = parseOptionalNumberField(
    input.sleepHours,
    'Sleep duration (hrs)',
    0,
    24,
    false,
  );
  if (!sleepHours.ok) return { valid: false, error: sleepHours.error };

  const movementMinutes = parseOptionalNumberField(
    input.movementMinutes,
    'Daily movement (min)',
    0,
    600,
    true,
  );
  if (!movementMinutes.ok) return { valid: false, error: movementMinutes.error };

  const restingHr = parseOptionalNumberField(
    input.restingHeartRateBpm,
    'Resting heart rate (bpm)',
    30,
    220,
    true,
  );
  if (!restingHr.ok) return { valid: false, error: restingHr.error };

  const systolic = parseOptionalNumberField(
    input.systolicMmHg,
    'Systolic blood pressure (mmHg)',
    60,
    250,
    true,
  );
  if (!systolic.ok) return { valid: false, error: systolic.error };

  const diastolic = parseOptionalNumberField(
    input.diastolicMmHg,
    'Diastolic blood pressure (mmHg)',
    40,
    150,
    true,
  );
  if (!diastolic.ok) return { valid: false, error: diastolic.error };

  if (
    (systolic.value !== undefined && diastolic.value === undefined) ||
    (systolic.value === undefined && diastolic.value !== undefined)
  ) {
    return {
      valid: false,
      error:
        'Enter both systolic and diastolic blood pressure readings, or leave both blank.',
    };
  }

  if (
    systolic.value !== undefined &&
    diastolic.value !== undefined &&
    systolic.value <= diastolic.value
  ) {
    return {
      valid: false,
      error:
        'Systolic blood pressure must be higher than diastolic blood pressure.',
    };
  }

  return {
    valid: true,
    normalized: {
      energyLevel: input.energyLevel,
      sleepQuality: input.sleepQuality,
      stressSelfRating: input.stressSelfRating,
      ...(sleepHours.value !== undefined ? { sleepHours: sleepHours.value } : {}),
      ...(movementMinutes.value !== undefined
        ? { movementMinutes: movementMinutes.value }
        : {}),
      ...(restingHr.value !== undefined
        ? { restingHeartRateBpm: restingHr.value }
        : {}),
      ...(systolic.value !== undefined ? { systolicMmHg: systolic.value } : {}),
      ...(diastolic.value !== undefined
        ? { diastolicMmHg: diastolic.value }
        : {}),
      moodNote: (input.moodNote ?? '').trim(),
    },
  };
}

export interface MinimalAiContextPayload {
  confirmedFindings: Array<{
    category: ReportCategory;
    testName: string;
    result: string;
    unit: string;
    reportDate: string;
    referenceRange: string;
    rangeStatus: RangeStatus;
    clinicalInterpretation?: string;
  }>;
  latestWellbeingCheckIn?: {
    date: string;
    energyLevel: number;
    sleepQuality: number;
    stressSelfRating: number;
    sleepHours?: number;
    movementMinutes?: number;
    restingHeartRateBpm?: number;
    systolicMmHg?: number;
    diastolicMmHg?: number;
  };
  question: string;
}

/**
 * Strips all unconfirmed findings, filenames, emails, user IDs, and freeform personal notes.
 * Sends ONLY the minimum confirmed report information needed.
 */
export function buildMinimalAiPayload(
  findings: ExtractedFinding[],
  question: string,
  latestCheckIn?: WellbeingCheckIn,
): MinimalAiContextPayload {
  const confirmedOnly = findings
    .filter((f) => f.confirmedByUser)
    .map((f) => ({
      category: f.category,
      testName: f.testName,
      result: f.result,
      unit: f.unit,
      reportDate: f.reportDate,
      referenceRange: f.referenceRange,
      rangeStatus: f.rangeStatus,
      ...(f.category === 'interpreted_genetic' && f.clinicalInterpretation
        ? { clinicalInterpretation: f.clinicalInterpretation }
        : {}),
    }));

  return {
    confirmedFindings: confirmedOnly,
    ...(latestCheckIn
      ? {
          latestWellbeingCheckIn: {
            date: latestCheckIn.date,
            energyLevel: latestCheckIn.energyLevel,
            sleepQuality: latestCheckIn.sleepQuality,
            stressSelfRating: latestCheckIn.stressSelfRating,
            ...(latestCheckIn.sleepHours !== undefined
              ? { sleepHours: latestCheckIn.sleepHours }
              : {}),
            ...(latestCheckIn.movementMinutes !== undefined
              ? { movementMinutes: latestCheckIn.movementMinutes }
              : {}),
            ...(latestCheckIn.restingHeartRateBpm !== undefined
              ? { restingHeartRateBpm: latestCheckIn.restingHeartRateBpm }
              : {}),
            ...(latestCheckIn.systolicMmHg !== undefined
              ? { systolicMmHg: latestCheckIn.systolicMmHg }
              : {}),
            ...(latestCheckIn.diastolicMmHg !== undefined
              ? { diastolicMmHg: latestCheckIn.diastolicMmHg }
              : {}),
          },
        }
      : {}),
    question: question.trim(),
  };
}

export interface RateLimitBucket {
  timestamps: number[];
}

export function checkRateLimit(
  bucket: RateLimitBucket,
  nowMs: number,
  limit: number,
  windowMs: number,
): { allowed: boolean; remaining: number; retryAfterSeconds: number } {
  const cutoff = nowMs - windowMs;
  bucket.timestamps = bucket.timestamps.filter((t) => t > cutoff);

  if (bucket.timestamps.length >= limit) {
    const oldest = bucket.timestamps[0];
    const retryAfterMs = Math.max(1000, oldest + windowMs - nowMs);
    return {
      allowed: false,
      remaining: 0,
      retryAfterSeconds: Math.ceil(retryAfterMs / 1000),
    };
  }

  bucket.timestamps.push(nowMs);
  return {
    allowed: true,
    remaining: Math.max(0, limit - bucket.timestamps.length),
    retryAfterSeconds: 0,
  };
}

